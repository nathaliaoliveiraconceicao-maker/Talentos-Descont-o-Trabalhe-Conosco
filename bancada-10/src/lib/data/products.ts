export function getProductBySlug(slug: string) {
  return products.find((p) => p.slug === slug)
}

export function getProductById(id: string) {
  return products.find((p) => p.id === id)
}

export function getRelatedProducts(product: Product, limit = 4) {
  return products
    .filter((p) => p.id !== product.id && p.categorySlugs.some((c) => product.categorySlugs.includes(c)))
    .slice(0, limit)
}

export function getFeaturedProducts(limit = 8) {
  return products.slice(0, limit)
}

export function getProductsByCategory(categorySlug: string) {
  return products.filter((p) => p.categorySlugs.includes(categorySlug))
}

export function getRetroProducts(limit = 8) {
  return products.filter((p) => p.kind === 'retro').slice(0, limit)
}

/**
 * Produtos "irmãos" do mesmo clube/temporada/tipo, mas em outra versão
 * (torcedor/jogador) — usados para oferecer a troca de versão na página do
 * produto. Hoje cada versão é cadastrada como um produto (SKU) separado;
 * se o catálogo real preferir um único produto com variação de versão,
 * este é o ponto a adaptar.
 */
export function findVersionSiblings(product: Product) {
  if (!product.club) return []
  return products.filter(
    (p) => p.id !== product.id && p.club === product.club && p.season === product.season && p.kind === product.kind
  )
}
